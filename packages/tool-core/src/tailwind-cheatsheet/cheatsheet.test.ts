import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import {
  categoryCounts,
  searchUtilities,
  TAILWIND_VERSION,
  UTILITIES,
  UTILITY_CATEGORY_IDS,
  UTILITY_CATEGORY_LABELS,
} from './index';

const root = fileURLToPath(new URL('../../../../', import.meta.url));

function pinnedTailwindVersion(): string {
  const manifest = JSON.parse(readFileSync(`${root}apps/web/package.json`, 'utf8')) as {
    devDependencies?: Record<string, string>;
  };
  const version = manifest.devDependencies?.tailwindcss;
  if (!version) throw new Error('apps/web does not depend on tailwindcss');
  return version;
}

describe('tailwind cheatsheet data', () => {
  it('is generated by the pinned Tailwind compiler and still matches it', () => {
    // A Tailwind upgrade changes the generated CSS; this fails until the data is
    // regenerated and the diff reviewed (DEC-40).
    const output = execFileSync(
      process.execPath,
      ['scripts/generate-tailwind-cheatsheet.mjs', '--check'],
      { cwd: root, encoding: 'utf8' },
    );
    expect(output).toContain('cheatsheet: generated.ts matches Tailwind');
  }, 60_000);

  it('records the version this repo pins', () => {
    expect(TAILWIND_VERSION).toBe(pinnedTailwindVersion());
  });

  it('has at least 250 entries, all with compiled CSS and our own note', () => {
    expect(UTILITIES.length).toBeGreaterThanOrEqual(250);
    for (const entry of UTILITIES) {
      expect(entry.css, `${entry.class} has no compiled CSS`).not.toBe('');
      expect(entry.note.length, `${entry.class} has no note`).toBeGreaterThanOrEqual(6);
      expect(entry.css).not.toMatch(/NaN|undefined/);
      expect(entry.class).not.toMatch(/\s/);
    }
  });

  it('uses every category and counts them truthfully', () => {
    const counts = categoryCounts();
    expect(counts.map((entry) => entry.id)).toEqual([...UTILITY_CATEGORY_IDS]);
    expect(counts.reduce((total, entry) => total + entry.count, 0)).toBe(UTILITIES.length);
    for (const count of counts) {
      expect(count.count, `${count.id} is empty`).toBeGreaterThan(0);
      expect(count.label).toBe(UTILITY_CATEGORY_LABELS[count.id]);
    }
  });

  it('keeps class names unique', () => {
    const names = UTILITIES.map((entry) => entry.class);
    expect(new Set(names).size).toBe(names.length);
  });
});

describe('tailwind cheatsheet search', () => {
  it('returns everything for an empty query', () => {
    expect(searchUtilities('').length).toBe(UTILITIES.length);
    expect(searchUtilities('   ').length).toBe(UTILITIES.length);
  });

  it('ranks an exact class match first and still searches words', () => {
    expect(searchUtilities('flex')[0]?.class).toBe('flex');
    expect(searchUtilities('grid-cols-3')[0]?.class).toBe('grid-cols-3');
    expect(searchUtilities('centre').some((entry) => entry.class === 'mx-auto')).toBe(true);
  });

  it('searches the CSS properties Tailwind emitted', () => {
    const display = searchUtilities('display');
    expect(display.some((entry) => entry.class === 'flex')).toBe(true);
    const margins = searchUtilities('margin');
    expect(margins.some((entry) => entry.class === 'm-2')).toBe(true);
    expect(margins.some((entry) => entry.class === 'flex')).toBe(false);
  });

  it('combines terms and filters by category', () => {
    expect(searchUtilities('padding').length).toBeGreaterThan(0);
    expect(searchUtilities('padding', 'spacing').length).toBeGreaterThan(0);
    expect(searchUtilities('gap-2', 'layout').length).toBe(0);
    expect(
      searchUtilities('gap', 'flexbox-grid').every((entry) => entry.category === 'flexbox-grid'),
    ).toBe(true);
  });
});
